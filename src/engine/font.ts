/** Every drawable character (the space has no glyph but keeps its slot). */
export const FONT_CHARS: readonly string[] = [' ', ...Object.keys(GLYPHS)];

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

/** Parsed glyph bitmaps: array of [x, y] ink pixels. */
const parsed = new Map<string, [number, number][]>();
for (const [ch, def] of Object.entries(GLYPHS)) {
  const pts: [number, number][] = [];
  def.split('|').forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') pts.push([x, y]);
  });
  parsed.set(ch, pts);
}

export function glyph(ch: string): [number, number][] {
  return parsed.get(ch) ?? parsed.get(ch.toUpperCase()) ?? parsed.get('?')!;
}

export function textWidth(text: string, scale = 1): number {
  if (!text.length) return 0;
  return (text.length * ADVANCE - 1) * scale;
}
